// UTF-8 bytes of a path, for the image_io.h functions.
std::string utf8Path(const std::filesystem::path & path)
{
    const auto utf8 = path.u8string();
    return std::string(reinterpret_cast<const char *>(utf8.data()), utf8.size());
}

// A scratch file in the temp directory, removed when it goes out of scope.
class TempFile
{
public:
    explicit TempFile(const std::string & name)
        : m_path(std::filesystem::temp_directory_path() / ("sabercat_image_compare_" + name))
    {
    }
    ~TempFile()
    {
        std::error_code ignored;
        std::filesystem::remove(m_path, ignored);
    }
    TempFile(const TempFile &) = delete;
    TempFile & operator=(const TempFile &) = delete;

    const std::filesystem::path & path() const { return m_path; }
    std::string utf8() const { return utf8Path(m_path); }

private:
    std::filesystem::path m_path;
};

void writeBytes(const std::filesystem::path & path, const unsigned char * data, size_t size)
{
    std::ofstream out(path, std::ios::binary | std::ios::trunc);
    out.write(reinterpret_cast<const char *>(data), static_cast<std::streamsize>(size));
}

