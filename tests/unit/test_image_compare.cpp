// A width x height image with every sample set to value.
Image makeImage(uint32_t width, uint32_t height, float value)
{
    Image image;
    image.width = width;
    image.height = height;
    image.rgb.assign(static_cast<size_t>(width) * height * 3, value);
    return image;
}

// A width x height image whose samples are given in row-major order.
Image makeImage(uint32_t width, uint32_t height, const std::vector<float> & samples)
{
    Image image;
    image.width = width;
    image.height = height;
    image.rgb = samples;
    return image;
}

// Runs fn and reports whether it threw std::invalid_argument.
template <typename Fn>
bool throwsInvalidArgument(Fn && fn)
{
    try
    {
        fn();
    }
    catch (const std::invalid_argument &)
    {
        return true;
    }
    catch (...)
    {
    }
    return false;
}

bool sameRgb(const Rgb8Image & image, size_t a, size_t b)
{
    return image.rgb[a * 3] == image.rgb[b * 3] && image.rgb[a * 3 + 1] == image.rgb[b * 3 + 1] &&
           image.rgb[a * 3 + 2] == image.rgb[b * 3 + 2];
}

int sumRgb(const Rgb8Image & image, size_t pixel)
{
    return image.rgb[pixel * 3] + image.rgb[pixel * 3 + 1] + image.rgb[pixel * 3 + 2];
}

